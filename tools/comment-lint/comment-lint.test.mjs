import { test } from "node:test";
import assert from "node:assert/strict";
import { findComments, lintSource } from "./comment-lint.mjs";

const lines = (source, language, jsx) => findComments(source, language, jsx).map((comment) => comment.line);

test("go flags line and block comments", () => {
  assert.deepEqual(lines('package main\n\n// explains\nfunc main() {}\n/* block */\n', "go"), [3, 5]);
});

test("go ignores comment markers inside strings, runes and raw strings", () => {
  const source = 'package main\n\nvar url = "https://example.com"\nvar raw = `/* not a comment */ // nope`\nvar slash = \'/\'\nvar quote = "say \\"//\\""\n';
  assert.deepEqual(lines(source, "go"), []);
});

test("go allows compiler directives", () => {
  assert.deepEqual(lines("//go:build linux\n\npackage main\n\n//go:generate stringer -type=Seat\n", "go"), []);
});

test("license header is allowed only before code", () => {
  const source = "// SPDX-License-Identifier: MIT\npackage main\n// Copyright later\n";
  assert.deepEqual(lines(source, "go"), [3]);
});

test("a doc block that only mentions licences is not a license header", () => {
  assert.deepEqual(lines("/**\n * Builds the copyright notice list from SPDX data.\n */\nexport {};\n", "js"), [1]);
  assert.deepEqual(lines("/*\n * Copyright (c) 2026 Vendor\n */\nexport {};\n", "js"), []);
});

test("generated files are skipped", () => {
  const source = "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage rulespb\n// field docs\n";
  assert.deepEqual(lintSource("server/gen/rules.pb.go", source), []);
  assert.deepEqual(lintSource("client/Assets/Gen/Rules.cs", "// <auto-generated>\nclass Rules {}\n// x\n"), []);
});

test("csharp flags xml doc and inline comments", () => {
  const source = "/// <summary>doc</summary>\nclass Tile\n{\n    int pips; // count\n}\n";
  assert.deepEqual(lines(source, "csharp"), [1, 4]);
});

test("csharp ignores markers inside every string form", () => {
  const source = [
    'var a = "http://x";',
    'var b = @"C:\\path\\// ""quoted""";',
    'var c = $"{name} // {Format("/* x */")}";',
    'var d = $@"{dir}\\// {{literal}}";',
    'var e = """',
    "  // inside raw",
    '  """;',
    'var f = $"""{value} // raw interpolation""";',
    "var g = '/';",
    "var h = @class;",
  ].join("\n");
  assert.deepEqual(lines(source, "csharp"), []);
});

test("csharp still finds a comment after strings", () => {
  assert.deepEqual(lines('var a = $"{x}";\nvar b = 1; // trailing\n', "csharp"), [2]);
});

test("js ignores markers inside strings, templates and regex literals", () => {
  const source = [
    'const url = "https://example.com";',
    "const single = 'a // b';",
    "const template = `x ${'//'} /* y */ ${`${\"//\"}`}`;",
    "const escaped = /https?:\\/\\//.test(url);",
    "const inClass = /[/*]/;",
    "const afterReturn = () => { return /a\\/b/; };",
  ].join("\n");
  assert.deepEqual(lines(source, "js"), []);
});

test("js division is not mistaken for a regex", () => {
  assert.deepEqual(lines("const ratio = total / count / 2; // halves\n", "js"), [1]);
  assert.deepEqual(lines("const x = (a) / b;\n/* block */\n", "js"), [2]);
});

test("tsx ignores jsx text but flags jsx comments", () => {
  const source = [
    "export function Rank() {",
    "  return (",
    '    <div className="rank" title={"a // b"}>',
    "      Player's rank: https://example.com",
    "      {/* hidden */}",
    "      <Badge level={level > 2 ? \"high\" : 'low'} />",
    "      <Seat",
    "        // attribute note",
    "        index={0}",
    "      />",
    "      <>{items.map((item) => <span key={item}>{item}</span>)}</>",
    "    </div>",
    "  );",
    "}",
    "// after",
  ].join("\n");
  assert.deepEqual(lines(source, "js", true), [5, 8, 15]);
});

test("ts generics are not jsx", () => {
  assert.deepEqual(lines("const map = new Map<string, number>();\nconst ok = a < b; // compare\n", "js"), [2]);
});

test("triple slash reference directive is allowed", () => {
  assert.deepEqual(lines('/// <reference types="next" />\nexport {};\n', "js"), []);
});

test("proto flags comments", () => {
  assert.deepEqual(lines('syntax = "proto3";\n// message docs\nmessage Tile { int32 left = 1; }\n', "proto"), [2]);
});
