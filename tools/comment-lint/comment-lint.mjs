import { readFileSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { extname } from "node:path";
import { pathToFileURL } from "node:url";

const languageByExtension = {
  ".go": "go",
  ".cs": "csharp",
  ".proto": "proto",
  ".ts": "js",
  ".tsx": "js",
  ".js": "js",
  ".jsx": "js",
  ".mjs": "js",
  ".cjs": "js",
};
const jsxExtensions = new Set([".tsx", ".jsx"]);
const identifierChar = /[A-Za-z0-9_$]/;
const punctuationBeforeExpression = new Set("(,=:[!&|?{};+-*%<>~^".split(""));
const wordsBeforeExpression = new Set([
  "return", "typeof", "case", "do", "else", "in", "of", "new",
  "delete", "void", "throw", "instanceof", "yield", "await",
]);
const generatedMarker = /Code generated .* DO NOT EDIT|<auto-generated|@generated/;
const licenseMarker = /SPDX-License-Identifier:|Copyright (\(c\)|©|\d{4})|Licensed under the/i;
const directivesByLanguage = {
  go: [/^\/\/go:/],
  js: [/^\/\/\/ <reference /],
  csharp: [],
  proto: [],
};
const ignoreFile = ".commentlintignore";

class Scanner {
  constructor(source, language, jsx) {
    this.source = source;
    this.language = language;
    this.jsx = jsx;
    this.index = 0;
    this.comments = [];
    this.lastSignificant = "";
    this.lastWord = "";
    this.codeSeen = false;
  }

  get char() {
    return this.source[this.index];
  }

  at(text) {
    return this.source.startsWith(text, this.index);
  }

  scanCode(untilClosingBrace) {
    let depth = 0;
    while (this.index < this.source.length) {
      if (this.at("//")) { this.lineComment(); continue; }
      if (this.at("/*")) { this.blockComment(); continue; }
      if (this.tryString()) continue;
      const char = this.char;
      if (char === "/" && this.language === "js" && this.expressionExpected()) { this.regex(); continue; }
      if (char === "<" && this.jsx && this.expressionExpected() && /[A-Za-z>]/.test(this.source[this.index + 1] ?? "")) {
        this.jsxElement();
        continue;
      }
      if (untilClosingBrace && char === "{") depth++;
      if (untilClosingBrace && char === "}") {
        if (depth === 0) {
          this.index++;
          this.markSignificant("}");
          return;
        }
        depth--;
      }
      this.consumeToken();
    }
  }

  consumeToken() {
    const char = this.char;
    if (/\s/.test(char)) {
      this.index++;
      return;
    }
    if (identifierChar.test(char)) {
      const start = this.index;
      while (this.index < this.source.length && identifierChar.test(this.char)) this.index++;
      this.lastSignificant = "a";
      this.lastWord = this.source.slice(start, this.index);
      this.codeSeen = true;
      return;
    }
    this.index++;
    this.markSignificant(char);
  }

  markSignificant(char) {
    this.lastSignificant = char;
    this.lastWord = "";
    this.codeSeen = true;
  }

  expectExpression() {
    this.lastSignificant = "(";
    this.lastWord = "";
  }

  expressionExpected() {
    if (this.lastSignificant === "") return true;
    if (this.lastSignificant === "a") return wordsBeforeExpression.has(this.lastWord);
    return punctuationBeforeExpression.has(this.lastSignificant);
  }

  tryString() {
    const char = this.char;
    if (this.language === "csharp") return this.csharpString();
    if (char === '"' || char === "'") {
      this.quoted(char);
      return true;
    }
    if (char !== "`" || this.language === "proto") return false;
    if (this.language === "go") this.rawUntilBacktick();
    else this.template();
    return true;
  }

  quoted(quote) {
    this.index++;
    while (this.index < this.source.length) {
      const char = this.char;
      if (char === "\\") {
        this.index += 2;
        continue;
      }
      this.index++;
      if (char === quote || char === "\n") break;
    }
    this.markSignificant("a");
  }

  rawUntilBacktick() {
    const end = this.source.indexOf("`", this.index + 1);
    this.index = end === -1 ? this.source.length : end + 1;
    this.markSignificant("a");
  }

  template() {
    this.index++;
    while (this.index < this.source.length) {
      const char = this.char;
      if (char === "\\") {
        this.index += 2;
        continue;
      }
      if (char === "`") {
        this.index++;
        break;
      }
      if (this.at("${")) {
        this.index += 2;
        this.expectExpression();
        this.scanCode(true);
        continue;
      }
      this.index++;
    }
    this.markSignificant("a");
  }

  csharpString() {
    const match = /^([$@]*)("{3,}|"|')/.exec(this.source.slice(this.index, this.index + 16));
    if (!match) return false;
    const [whole, prefix, quotes] = match;
    if (quotes === "'") {
      if (prefix) return false;
      this.quoted("'");
      return true;
    }
    this.index += whole.length;
    const dollarCount = prefix.split("$").length - 1;
    if (quotes.length >= 3) this.csharpRawString(quotes, dollarCount);
    else this.csharpRegularString(prefix.includes("@"), dollarCount > 0);
    this.markSignificant("a");
    return true;
  }

  csharpRegularString(verbatim, interpolated) {
    while (this.index < this.source.length) {
      const char = this.char;
      const next = this.source[this.index + 1];
      if (!verbatim && char === "\\") { this.index += 2; continue; }
      if (char === '"' && verbatim && next === '"') { this.index += 2; continue; }
      if (char === '"') { this.index++; return; }
      if (interpolated && char === "{" && next === "{") { this.index += 2; continue; }
      if (interpolated && char === "{") {
        this.index++;
        this.expectExpression();
        this.scanCode(true);
        continue;
      }
      if (!verbatim && char === "\n") return;
      this.index++;
    }
  }

  csharpRawString(quotes, dollarCount) {
    const interpolationStart = "{".repeat(Math.max(dollarCount, 1));
    while (this.index < this.source.length) {
      if (this.at(quotes)) {
        this.index += quotes.length;
        return;
      }
      if (dollarCount > 0 && this.at(interpolationStart)) {
        this.index += interpolationStart.length;
        this.expectExpression();
        this.scanCode(true);
        continue;
      }
      this.index++;
    }
  }

  regex() {
    this.index++;
    let inClass = false;
    while (this.index < this.source.length) {
      const char = this.char;
      if (char === "\\") { this.index += 2; continue; }
      if (char === "\n") break;
      this.index++;
      if (inClass) {
        if (char === "]") inClass = false;
        continue;
      }
      if (char === "[") inClass = true;
      else if (char === "/") break;
    }
    while (this.index < this.source.length && /[a-z]/i.test(this.char)) this.index++;
    this.markSignificant("a");
  }

  jsxElement() {
    let depth = 0;
    while (this.index < this.source.length) {
      if (this.char === "<") {
        const closing = this.source[this.index + 1] === "/";
        const selfClosing = this.jsxTag();
        if (closing) depth--;
        else if (!selfClosing) depth++;
        if (depth <= 0) break;
        continue;
      }
      if (this.char === "{") {
        this.index++;
        this.expectExpression();
        this.scanCode(true);
        continue;
      }
      this.index++;
    }
    this.markSignificant("a");
  }

  jsxTag() {
    this.index++;
    while (this.index < this.source.length) {
      const char = this.char;
      if (this.at("//")) { this.lineComment(); continue; }
      if (this.at("/*")) { this.blockComment(); continue; }
      if (char === '"' || char === "'") {
        this.quoted(char);
        continue;
      }
      if (char === "{") {
        this.index++;
        this.expectExpression();
        this.scanCode(true);
        continue;
      }
      if (char === ">") {
        const selfClosing = this.source[this.index - 1] === "/";
        this.index++;
        return selfClosing;
      }
      this.index++;
    }
    return false;
  }

  lineComment() {
    const start = this.index;
    const end = this.source.indexOf("\n", start);
    this.index = end === -1 ? this.source.length : end;
    this.record(start);
  }

  blockComment() {
    const start = this.index;
    const end = this.source.indexOf("*/", start + 2);
    this.index = end === -1 ? this.source.length : end + 2;
    this.record(start);
  }

  record(start) {
    const text = this.source.slice(start, this.index);
    if (directivesByLanguage[this.language].some((directive) => directive.test(text))) return;
    if (!this.codeSeen && licenseMarker.test(text)) return;
    this.comments.push({ line: lineNumberAt(this.source, start), text: text.split("\n")[0].trim() });
  }
}

function lineNumberAt(source, index) {
  let line = 1;
  for (let position = 0; position < index; position++) if (source[position] === "\n") line++;
  return line;
}

export function languageOf(path) {
  return languageByExtension[extname(path).toLowerCase()];
}

export function findComments(source, language, jsx = false) {
  const scanner = new Scanner(source, language, jsx);
  scanner.scanCode(false);
  return scanner.comments;
}

export function lintSource(path, source) {
  const language = languageOf(path);
  if (!language || generatedMarker.test(source.slice(0, 1000))) return [];
  return findComments(source, language, jsxExtensions.has(extname(path).toLowerCase()));
}

function git(args) {
  return execFileSync("git", args, { encoding: "utf8", maxBuffer: 1 << 28 });
}

function candidateFiles(staged) {
  const args = staged ? ["diff", "--cached", "--name-only", "--diff-filter=ACMR", "-z"] : ["ls-files", "-z"];
  return git(args).split("\0").filter(Boolean);
}

function ignorePatterns() {
  if (!existsSync(ignoreFile)) return [];
  return readFileSync(ignoreFile, "utf8").split(/\r?\n/).map((line) => line.trim()).filter(Boolean);
}

function isIgnored(path, patterns) {
  return patterns.some((pattern) => {
    if (pattern.endsWith("/")) return path.startsWith(pattern);
    if (pattern.startsWith("*")) return path.endsWith(pattern.slice(1));
    return path === pattern;
  });
}

function readSource(path, staged) {
  return staged ? git(["show", `:${path}`]) : readFileSync(path, "utf8");
}

function main(argv) {
  const staged = argv.includes("--staged");
  const explicitFiles = argv.filter((argument) => !argument.startsWith("--"));
  const patterns = ignorePatterns();
  const files = (explicitFiles.length > 0 ? explicitFiles : candidateFiles(staged))
    .map((path) => path.replaceAll("\\", "/"))
    .filter((path) => languageOf(path) && !isIgnored(path, patterns) && (staged || existsSync(path)));
  let violations = 0;
  for (const path of files) {
    for (const comment of lintSource(path, readSource(path, staged))) {
      console.error(`${path}:${comment.line}: comment not allowed: ${comment.text}`);
      violations++;
    }
  }
  if (violations > 0) {
    console.error(`comment-lint: ${violations} comment(s) found. Names must explain intent, see CLAUDE.md.`);
    process.exit(1);
  }
  console.log(`comment-lint: ${files.length} file(s) clean`);
}

